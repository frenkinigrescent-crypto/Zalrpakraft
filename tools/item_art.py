def lerp(a, b, t):
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(4))


def ramp(dark, light, n=5):
    d, l = hx(dark), hx(light)
    return [lerp(d, l, i / (n - 1)) for i in range(n)]


def sphere(dark, light, outline, r=6.6, cx=7.5, cy=7.5):
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = im.load()
    rp = ramp(dark, light)
    L = (-0.55, -0.62, 0.56)
    for y in range(16):
        for x in range(16):
            dx, dy = (x - cx) / r, (y - cy) / r
            d2 = dx * dx + dy * dy
            if d2 > 1.0:
                continue
            if d2 > (1 - 1.15 / r) ** 2:
                px[x, y] = hx(outline)
                continue
            dz = math.sqrt(max(0.0, 1 - d2))
            lum = max(0.0, dx * L[0] + dy * L[1] + dz * L[2])
            lum = lum ** 1.2
            i = min(4, int(lum * 5.2))
            px[x, y] = rp[i]
    px[5, 4] = hx("#FFFFFFE0")
    px[4, 5] = hx("#FFFFFFA0")
    px[5, 5] = lerp(px[5, 5], hx("#FFFFFF"), 0.4)
    return im


def put(im, pts, col):
    px = im.load()
    c = hx(col)
    for (x, y) in pts:
        if 0 <= x < 16 and 0 <= y < 16:
            px[x, y] = c


def disc(cx, cy, r):
    return [(x, y) for y in range(16) for x in range(16) if (x - cx) ** 2 + (y - cy) ** 2 <= r * r]


def ringpts(cx, cy, r0, r1):
    return [(x, y) for y in range(16) for x in range(16) if r0 * r0 < (x - cx) ** 2 + (y - cy) ** 2 <= r1 * r1]


def overlay(im, rows, pal, ox, oy):
    px = im.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != "." and 0 <= ox + x < 16 and 0 <= oy + y < 16:
                px[ox + x, oy + y] = hx(pal[ch])


